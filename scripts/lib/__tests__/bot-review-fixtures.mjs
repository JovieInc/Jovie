/** gh fake: first call reads `threads`, the rest succeed and are recorded. */
export function fakeGh(threads) {
  const calls = [];
  const gh = async args => {
    calls.push(args);
    if (args.some(arg => arg.startsWith('query=query'))) {
      const read = liveRead(threads);
      const body = JSON.parse(read.stdout);
      const id = args.find(arg => arg.startsWith('id='))?.slice(3);
      body.data.node = threads.find(thread => thread.id === id);
      return { code: 0, stdout: JSON.stringify(body) };
    }
    return { code: 0, stdout: '{}' };
  };
  return { gh, calls };
}

/** Linear intake fake that dedupes by fingerprint like the real upsert. */
export function fakeIntake() {
  const issues = new Map();
  const upserts = [];
  return {
    issues,
    upserts,
    intake: {
      apiKey: 'lin_test',
      enabled: true,
      findLabel: async ({ name }) => ({ ok: true, id: `label-${name}` }),
      upsert: async issue => {
        upserts.push(issue);
        const known = issues.get(issue.fingerprint);
        if (known) return { ok: true, action: 'updated', ...known };
        const filed = {
          identifier: `JOV-${90000 + issues.size}`,
          url: `https://linear.app/jovie/issue/JOV-${90000 + issues.size}`,
        };
        issues.set(issue.fingerprint, filed);
        return { ok: true, action: 'created', ...filed };
      },
    },
  };
}

