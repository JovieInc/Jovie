import { describe, expect, it } from 'vitest';
import {
  isReviewBot,
  RESOLVE_MUTATION,
  resolveBotThreads,
  selectResolvableThreads,
  threadSkipReason,
} from '../bot-review-threads.mjs';
import {
  analyzePrCommentData,
  classifyComment,
  isActionableInlineComment,
  isAddressedReply,
  isSummaryNoise,
} from '../pr-comment-analysis.mjs';

const pr = {
  number: 123,
  title: 'feat(testing): add nightly testing agent',
  head: 'codex/nightly-testing-agent',
  author: 'itstimwhite',
  labels: ['testing'],
  url: 'https://github.com/JovieInc/Jovie/pull/123',
};

function inline({
  body,
  author = 'coderabbitai[bot]',
  path = 'apps/web/x.ts',
}) {
  return {
    body,
    html_url: 'https://github.com/JovieInc/Jovie/pull/123#discussion',
    line: 42,
    path,
    position: 5,
    user: { login: author },
  };
}

describe('pr-comment-analysis', () => {
  it('ignores bot summary noise', () => {
    expect(
      isSummaryNoise({
        body: '<!-- This is an auto-generated comment: summarize by coderabbit.ai -->',
      })
    ).toBe(true);
    expect(
      isActionableInlineComment(
        inline({
          body: '<h3>Greptile Summary</h3> This PR changes tests.',
          author: 'greptile-apps[bot]',
        })
      )
    ).toBe(false);
  });

  it('ignores addressed confirmations and resolved replies', () => {
    expect(
      isAddressedReply({
        body: '`@itstimwhite`, confirmed -- this fix closes the gap.',
      })
    ).toBe(true);
    expect(
      isActionableInlineComment(
        inline({
          body: 'Fixed in abc123: the report now includes validation totals.',
          author: 'itstimwhite',
        })
      )
    ).toBe(false);
  });

  it('counts actionable CodeRabbit, Greptile, Sentry, and human findings', () => {
    const data = {
      repo: 'JovieInc/Jovie',
      since: '2026-05-01T00:00:00.000Z',
      pull_count: 1,
      pulls: [
        {
          pr,
          issueComments: [
            {
              body: '## CI Summary\nAll green.',
              user: { login: 'github-actions[bot]' },
            },
          ],
          reviews: [],
          reviewComments: [
            inline({
              body: '_Potential issue_ **Reject candidate commands whose cwd escapes the repository.**',
            }),
            inline({
              body: '<a><img alt="P2"></a> **Risk selection always ignores historical failures**',
              author: 'greptile-apps[bot]',
            }),
            inline({
              body: '**Bug:** The script accesses candidate.expectedSignal.kind without checking if expectedSignal exists.',
              author: 'sentry[bot]',
            }),
            inline({
              body: 'This should fail closed; the current path silently omits validation output.',
              author: 'human-reviewer',
            }),
            inline({
              body: '`@itstimwhite`, confirmed -- thanks for the fix.',
            }),
          ],
        },
      ],
    };

    const analysis = analyzePrCommentData(data);

    expect(analysis.rawCounts.issue).toBe(1);
    expect(analysis.rawCounts.inline).toBe(5);
    expect(analysis.actionableInlineCount).toBe(4);
    expect(analysis.agentOffenderPrs[0].pr.number).toBe(123);
  });

  it('detects recurring hardening categories', () => {
    expect(
      classifyComment({
        path: '.github/workflows/nightly-tests.yml',
        body: 'Both nightly workflows now share the same cron slot.',
      })
    ).toBe('workflow-scheduling');
    expect(
      classifyComment({
        body: 'Reject candidate commands whose cwd escapes the repository.',
      })
    ).toBe('path-scope');
    expect(
      classifyComment({
        body: 'emit-delta silently omits candidate-validation.json from the report.',
      })
    ).toBe('silent-reporting');
    expect(
      classifyComment({
        body: 'expectedSignal is missing and the empty candidates directory throws EISDIR.',
      })
    ).toBe('malformed-state');
  });
});

describe('bot review thread resolution on a green head', () => {
  const HEAD = 'a'.repeat(40);
  const sentry = { __typename: 'Bot', login: 'sentry' };
  const rabbit = { __typename: 'Bot', login: 'coderabbitai' };
  const human = { __typename: 'User', login: 'itstimwhite' };
  const FOOTER =
    '\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_';
  const thread = (id, comments, extra = {}) => ({
    id,
    isResolved: false,
    comments: { pageInfo: { hasNextPage: false }, nodes: comments },
    ...extra,
  });
  const c = (author, body = 'finding') => ({ author, body });
  const liveRead = threads => ({
    code: 0,
    stdout: JSON.stringify({
      data: {
        repository: {
          pullRequest: {
            state: 'OPEN',
            headRefOid: HEAD,
            reviewThreads: { nodes: threads },
          },
        },
      },
    }),
  });

  it('knows the review bots by GraphQL type and login', () => {
    expect(isReviewBot(sentry)).toBe(true);
    expect(isReviewBot({ __typename: 'Bot', login: 'coderabbitai[bot]' })).toBe(
      true
    );
    // A user account named like a bot is a human.
    expect(isReviewBot({ __typename: 'User', login: 'sentry' })).toBe(false);
    expect(isReviewBot({ __typename: 'Bot', login: 'dependabot' })).toBe(false);
  });

  it('resolves bot threads, alone or answered by a bot or an agent', () => {
    expect(threadSkipReason(thread('T1', [c(sentry)]))).toBeNull();
    expect(
      threadSkipReason(thread('T2', [c(rabbit), c(rabbit, 'Resolved in abc')]))
    ).toBeNull();
    expect(
      threadSkipReason(thread('T3', [c(sentry), c(human, `Fixed.${FOOTER}`)]))
    ).toBeNull();
  });

  it('never touches a human thread or a bot thread a human replied in', () => {
    expect(threadSkipReason(thread('H1', [c(human)]))).toBe('not-bot');
    expect(
      threadSkipReason(thread('H2', [c(sentry), c(human, 'Is this real?')]))
    ).toBe('human-reply');
  });

  it('leaves resolved, incomplete and malformed threads alone', () => {
    expect(
      threadSkipReason(thread('R', [c(sentry)], { isResolved: true }))
    ).toBe('resolved');
    const paged = thread('P', [c(sentry)]);
    paged.comments.pageInfo.hasNextPage = true;
    expect(threadSkipReason(paged)).toBe('incomplete');
    expect(threadSkipReason(thread('E', []))).toBe('no-comments');
    expect(threadSkipReason({ isResolved: false })).toBe('malformed');
  });

  it('acts only on the open PR at the exact green head', () => {
    const live = JSON.parse(
      liveRead([thread('T1', [c(sentry)]), thread('H1', [c(human)])]).stdout
    ).data.repository.pullRequest;
    expect(selectResolvableThreads(live, HEAD)).toEqual({
      skip: null,
      ids: ['T1'],
    });
    expect(selectResolvableThreads(live, 'b'.repeat(40)).skip).toBe(
      'head-moved'
    );
    expect(
      selectResolvableThreads({ ...live, state: 'MERGED' }, HEAD).skip
    ).toBe('not-open');
    expect(selectResolvableThreads(live, 'nope').skip).toBe('bad-head');
  });

  it('resolves only the bot threads through the gh client', async () => {
    const calls = [];
    const gh = async args => {
      calls.push(args);
      return calls.length === 1
        ? liveRead([thread('T1', [c(sentry)]), thread('H1', [c(human)])])
        : { code: 0, stdout: '{}' };
    };
    const out = await resolveBotThreads({
      repo: 'JovieInc/Jovie',
      pr: 7,
      head: HEAD,
      gh,
      log: () => {},
    });
    expect(out).toEqual({ resolved: ['T1'], failed: [], skip: null });
    expect(calls).toHaveLength(2);
    expect(calls[1]).toContain(`query=${RESOLVE_MUTATION}`);
    expect(calls[1]).toContain('id=T1');
  });

  it('dry-run and failed reads mutate nothing', async () => {
    const calls = [];
    const dry = await resolveBotThreads({
      repo: 'JovieInc/Jovie',
      pr: 7,
      head: HEAD,
      dryRun: true,
      gh: async args => {
        calls.push(args);
        return liveRead([thread('T1', [c(sentry)])]);
      },
      log: () => {},
    });
    expect(dry.resolved).toEqual(['T1']);
    expect(calls).toHaveLength(1);
    const failed = await resolveBotThreads({
      repo: 'JovieInc/Jovie',
      pr: 7,
      head: HEAD,
      gh: async () => ({ code: 75, stdout: '' }),
      log: () => {},
    });
    expect(failed).toEqual({ resolved: [], failed: [], skip: 'read-failed' });
  });
});
