#!/usr/bin/env node
/**
 * Credentials and spend registry check (metadata only).
 *
 *   node scripts/credentials-spend-check.mjs [--live] [--receipt <jsonl>]
 *     [--file-linear] [--fail-on critical|high] [--json]
 *
 * --live reads, when their credentials are present in the environment or on
 * the host: AI Gateway credits (AI_GATEWAY_API_KEY or VERCEL_OIDC_TOKEN),
 * Summer's dated grants on Vercel (VERCEL_READONLY_TOKEN, VERCEL_TOKEN, or the
 * local Vercel CLI login with --vercel-cli-auth), Gem's Codex ledger, and
 * Summer's provider-trial ledger (SUMMER_PROVIDER_TRIAL_LEDGER: a file path or
 * https URL, optional bearer SUMMER_PROVIDER_TRIAL_LEDGER_TOKEN).
 * Every run records stage timestamps; --receipt appends the run record.
 * --file-linear files each alerting finding through the remediation intake
 * (LINEAR_API_KEY, or an app's OAuth LINEAR_ACCESS_TOKEN), the same path the
 * nightly remediation sweep uses.
 */

import { randomUUID } from 'node:crypto';
import { appendFileSync, mkdirSync, readFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  codexOverlays,
  grantOverlays,
  localVercelToken,
  readCodexAccounts,
  readGatewayCredits,
  readProviderTrialLedger,
  readSummerGrants,
} from './lib/credentials-live-reads.mjs';
import {
  evaluateRegistry,
  planFindings,
  RUN_SCHEMA,
} from './lib/credentials-registry.mjs';

const REPO_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const CREDENTIALS_PATH = resolve(
  REPO_ROOT,
  'ops/registry/credentials.json'
);
export const SPEND_PATH = resolve(REPO_ROOT, 'ops/registry/spend.json');
/** Third-party grants on Tim's/org accounts, one JSON object per line. */
export const GRANTS_PATH = resolve(
  REPO_ROOT,
  'ops/registry/third-party-grants.jsonl'
);
/** Generated by scripts/credentials-inventory-collect.mjs: store names only. */
export const INVENTORY_PATH = resolve(
  REPO_ROOT,
  'ops/registry/inventory.gen.json'
);
export const GATEWAY_SPEND_ID = 'vercel-ai-gateway-credits';

export function loadRegistry({
  credentialsPath = CREDENTIALS_PATH,
  spendPath = SPEND_PATH,
  inventoryPath = INVENTORY_PATH,
  grantsPath = GRANTS_PATH,
} = {}) {
  const credentials = JSON.parse(readFileSync(credentialsPath, 'utf8'));
  const inventory = JSON.parse(readFileSync(inventoryPath, 'utf8'));
  return {
    credentials: { ...credentials, stores: inventory.stores ?? [] },
    spend: JSON.parse(readFileSync(spendPath, 'utf8')),
    thirdPartyGrants: readFileSync(grantsPath, 'utf8')
      .split('\n')
      .filter(line => line.trim())
      .map(line => JSON.parse(line)),
  };
}

/** Times a stage; failures are recorded, not thrown, so one reader cannot hide the rest. */
async function stage(stages, name, now, fn) {
  const startedMs = now();
  const record = { name, startedAt: new Date(startedMs).toISOString() };
  try {
    const result = await fn();
    record.ok = result?.ok !== false;
    if (result?.ok === false) record.reason = result.reason;
    return result;
  } catch (error) {
    record.ok = false;
    record.reason = error instanceof Error ? error.message : String(error);
    return { ok: false, reason: record.reason };
  } finally {
    const finishedMs = now();
    record.finishedAt = new Date(finishedMs).toISOString();
    record.ms = finishedMs - startedMs;
    stages.push(record);
  }
}

/**
 * @param {{
 *   env?: Record<string, string | undefined>,
 *   live?: boolean,
 *   vercelCliAuth?: boolean,
 *   codexPath?: string,
 *   trialLedger?: string,
 *   fetchImpl?: typeof fetch,
 *   now?: () => number,
 *   registry?: { credentials: any, spend: any, thirdPartyGrants?: any[] },
 *   fileLinear?: boolean,
 *   upsert?: (plan: any) => Promise<any>,
 * }} [options]
 */
export async function runCheck({
  env = process.env,
  live = false,
  vercelCliAuth = false,
  codexPath,
  trialLedger,
  fetchImpl = fetch,
  now = Date.now,
  registry,
  fileLinear = false,
  upsert,
} = {}) {
  const runStartedMs = now();
  const stages = [];
  const loaded = await stage(stages, 'load-registry', now, async () => ({
    ok: true,
    value: registry ?? loadRegistry(),
  }));
  if (!loaded.ok) throw new Error(`registry unreadable: ${loaded.reason}`);
  const { credentials, spend, thirdPartyGrants = [] } = loaded.value;
  const overlay = { spend: {}, credentials: [] };
  const reads = {};
  if (live) {
    const gateway = await stage(stages, 'read-gateway-credits', now, () =>
      readGatewayCredits({
        token: env.AI_GATEWAY_API_KEY || env.VERCEL_OIDC_TOKEN,
        fetchImpl,
        now,
      })
    );
    reads.gatewayCredits = gateway.ok ? 'ok' : gateway.reason;
    if (gateway.ok) overlay.spend[GATEWAY_SPEND_ID] = gateway.value;

    const vercelToken =
      env.VERCEL_READONLY_TOKEN ||
      env.VERCEL_TOKEN ||
      (vercelCliAuth ? localVercelToken() : null);
    const grants = await stage(stages, 'read-summer-grants', now, () =>
      readSummerGrants({ token: vercelToken, fetchImpl })
    );
    reads.summerGrants = grants.ok
      ? `ok:${grants.value.length}`
      : grants.reason;
    if (grants.ok)
      overlay.credentials.push(
        ...grantOverlays(grants.value, credentials.credentials)
      );

    const codex = await stage(stages, 'read-codex-ledger', now, async () =>
      readCodexAccounts(codexPath)
    );
    reads.codexLedger = codex.ok ? `ok:${codex.value.length}` : codex.reason;
    if (codex.ok) {
      overlay.credentials.push(...codexOverlays(codex.value));
      reads.codexAuthFailures = codex.value
        .filter(account => account.lastKind === 'auth')
        .map(account => account.account);
    }

    const trial = await stage(stages, 'read-provider-trial-ledger', now, () =>
      readProviderTrialLedger({
        source: trialLedger ?? env.SUMMER_PROVIDER_TRIAL_LEDGER,
        token: env.SUMMER_PROVIDER_TRIAL_LEDGER_TOKEN,
        fetchImpl,
        now,
      })
    );
    reads.providerTrialLedger = trial.ok ? 'ok' : trial.reason;
    if (trial.ok) Object.assign(overlay.spend, trial.value);
  }
  const evaluated = await stage(stages, 'evaluate', now, async () => ({
    ok: true,
    value: evaluateRegistry({
      credentials,
      spend,
      thirdPartyGrants,
      nowMs: now(),
      live: overlay,
    }),
  }));
  if (!evaluated.ok) throw new Error(evaluated.reason);
  const result = evaluated.value;
  const plans = planFindings(result.findings);
  let filed = [];
  if (fileLinear) {
    const filing = await stage(stages, 'file-linear', now, async () => {
      for (const plan of plans) {
        const outcome = await upsert({
          ...plan,
          apiKey: env.LINEAR_API_KEY || env.LINEAR_ACCESS_TOKEN,
        });
        filed.push({
          fingerprint: plan.fingerprint,
          action: outcome?.ok ? outcome.action : 'failed',
          identifier: outcome?.identifier ?? null,
          reason: outcome?.ok ? undefined : outcome?.reason,
        });
      }
      return { ok: filed.every(item => item.action !== 'failed') };
    });
    if (!filing.ok && !filed.length) filed = [{ action: 'failed' }];
  }
  const finishedMs = now();
  const run = {
    schema: RUN_SCHEMA,
    runId: randomUUID(),
    host:
      env.GITHUB_ACTIONS === 'true'
        ? 'github-actions'
        : env.HOSTNAME || 'local',
    startedAt: new Date(runStartedMs).toISOString(),
    finishedAt: new Date(finishedMs).toISOString(),
    durationMs: finishedMs - runStartedMs,
    live,
    reads,
    stages,
    counts: result.counts,
    alerting: plans.length,
  };
  return { run, findings: result.findings, spend: result.spend, plans, filed };
}

function argument(name) {
  const index = process.argv.indexOf(name);
  return index === -1 ? null : process.argv[index + 1];
}

function summary(report) {
  const lines = [
    `credentials-spend-check ${report.run.finishedAt} (${report.run.durationMs} ms, live=${report.run.live})`,
    `counts: ${JSON.stringify(report.run.counts.bySeverity)}; ${report.run.counts.credentials} credentials, ${report.run.counts.secretNames} secret names (${report.run.counts.unclaimedSecretNames} unclaimed), ${report.run.counts.spendLines} spend lines`,
  ];
  for (const item of report.findings)
    lines.push(`[${item.severity}] ${item.fingerprint}: ${item.message}`);
  return lines.join('\n');
}

async function main() {
  const failOn = argument('--fail-on');
  const receipt = argument('--receipt');
  const fileLinear = process.argv.includes('--file-linear');
  const upsert = fileLinear
    ? (await import('./lib/linear-issue-intake.mjs'))
        .upsertLinearIssueByTitleFingerprint
    : undefined;
  const report = await runCheck({
    live: process.argv.includes('--live'),
    vercelCliAuth: process.argv.includes('--vercel-cli-auth'),
    codexPath: argument('--codex-accounts') ?? undefined,
    trialLedger: argument('--trial-ledger') ?? undefined,
    fileLinear,
    upsert,
  });
  if (receipt) {
    mkdirSync(dirname(resolve(receipt)), { recursive: true });
    appendFileSync(resolve(receipt), `${JSON.stringify(report.run)}\n`);
  }
  if (process.argv.includes('--json'))
    process.stdout.write(`${JSON.stringify(report, null, 2)}\n`);
  else process.stdout.write(`${summary(report)}\n`);
  const failing =
    failOn === 'critical'
      ? ['critical']
      : failOn === 'high'
        ? ['critical', 'high']
        : [];
  if (report.findings.some(item => failing.includes(item.severity)))
    process.exitCode = 2;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  main().catch(error => {
    process.stderr.write(
      `${error instanceof Error ? error.message : String(error)}\n`
    );
    process.exit(1);
  });
}
