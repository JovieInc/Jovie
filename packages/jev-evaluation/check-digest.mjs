import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { IMPLEMENTATION_SHA256 } from './implementation-digest.mjs';

const files = ['gateway.mjs', 'shadow.mjs', 'fingerprint.mjs'];
const hash = createHash('sha256');
for (const file of files) {
  hash
    .update(file)
    .update('\0')
    .update(readFileSync(new URL(file, import.meta.url)))
    .update('\0');
}
const digest = hash.digest('hex');
if (process.argv.includes('--write')) {
  writeFileSync(
    new URL('./implementation-digest.mjs', import.meta.url),
    `// Generated by check-digest.mjs --write; verified by run-outcome:check.\nexport const IMPLEMENTATION_SHA256 =\n  '${digest}';\n`
  );
} else if (digest !== IMPLEMENTATION_SHA256) {
  throw new Error(
    'Jev implementation digest is stale; run check-digest.mjs --write'
  );
}
