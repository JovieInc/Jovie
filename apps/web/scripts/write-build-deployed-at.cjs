'use strict';

const { writeFileSync } = require('node:fs');
const path = require('node:path');

const DEFAULT_OUTPUT = path.join(
  __dirname,
  '../lib/observability/build-deployed-at.generated.ts'
);

const HEADER = `// Generated by scripts/write-build-deployed-at.cjs during \`next build\`.
// Committed as null so dev, tests, and typecheck stay clock-free.
// Production bundles inline this epoch. Request handlers must not replace it
// with the request clock (JOV-8658).
`;

/** Epoch milliseconds, or null when the value is not a real timestamp. */
function parseTimestampMs(value) {
  if (typeof value === 'number') return acceptEpochMs(value);
  if (typeof value !== 'string') return null;
  const trimmed = value.trim();
  if (!trimmed) return null;
  if (/^\d{10}$/.test(trimmed)) return acceptEpochMs(Number(trimmed) * 1000);
  if (/^\d{13}$/.test(trimmed)) return acceptEpochMs(Number(trimmed));
  if (/^\d+$/.test(trimmed)) return null;
  return acceptEpochMs(Date.parse(trimmed));
}

function acceptEpochMs(ms) {
  if (!Number.isInteger(ms)) return null;
  // 2001-09-09 through 2286-11-20. Rejects seconds-as-millis and junk.
  if (ms < 1_000_000_000_000 || ms > 9_999_999_999_999) return null;
  return ms;
}

/**
 * Build-start stamp. Explicit deploy/build env wins; otherwise `nowMs` runs
 * once, here, not on a request.
 */
function resolveBuildStampMs({
  vercelDeploymentTime,
  buildDeployedAt,
  nowMs,
} = {}) {
  return (
    parseTimestampMs(vercelDeploymentTime) ??
    parseTimestampMs(buildDeployedAt) ??
    parseTimestampMs(typeof nowMs === 'function' ? nowMs() : undefined)
  );
}

function renderBuildDeployedAtModule(deployedAt) {
  const literal = deployedAt == null ? 'null' : String(deployedAt);
  return `${HEADER}export const BUILD_DEPLOYED_AT_MS: number | null = ${literal};\n`;
}

let cachedDefaultStamp;

function stampFromEnv(options) {
  return resolveBuildStampMs({
    vercelDeploymentTime:
      options.vercelDeploymentTime ?? process.env.VERCEL_DEPLOYMENT_TIME,
    buildDeployedAt:
      options.buildDeployedAt ?? process.env.JOVIE_BUILD_DEPLOYED_AT,
    nowMs: options.nowMs ?? Date.now,
  });
}

function writeBuildDeployedAt(options = {}) {
  const useDefault =
    options.outputPath == null &&
    options.nowMs == null &&
    options.vercelDeploymentTime == null &&
    options.buildDeployedAt == null;
  // next build can load next.config more than once. Keep the first stamp so
  // a second pass does not rewrite the module mid-compile.
  const deployedAt = useDefault
    ? (cachedDefaultStamp ??= stampFromEnv(options))
    : stampFromEnv(options);
  const outputPath = options.outputPath ?? DEFAULT_OUTPUT;
  writeFileSync(outputPath, renderBuildDeployedAtModule(deployedAt));
  return deployedAt;
}

module.exports = {
  DEFAULT_OUTPUT,
  parseTimestampMs,
  renderBuildDeployedAtModule,
  resolveBuildStampMs,
  writeBuildDeployedAt,
};

if (require.main === module) {
  writeBuildDeployedAt();
}
