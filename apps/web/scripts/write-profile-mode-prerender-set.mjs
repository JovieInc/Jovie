#!/usr/bin/env node
/**
 * Writes lib/routing/generated/profile-mode-prerender-set.ts at build time.
 *
 * The proxy's `?mode=` rewrite (getProfileModeQueryRewrite) must only send a
 * request to the private profile-mode-render destination when the build
 * actually prerendered that (handle, mode) document. The prerender set is
 * computed during `next build` by getProfileModeRenderStaticParams, which
 * returns [] when the build has no database — and an ISR fallback render for
 * a pair the build did not prerender serves Next's flight-only __next_error__
 * shell, not the profile (JOV-12481; observed in the daily workflow_dispatch
 * CI lanes where ci-build-public runs without a DATABASE_URL, and on the
 * /dualipa/notifications -> /dualipa?mode=subscribe chain Lighthouse audits).
 *
 * This script answers the same question the build's generateStaticParams
 * answers — which alias-budget pairs have a public profile in the build
 * database — seconds before `next build` runs, and persists it as a module
 * the proxy can import. When the build database is unreachable it writes an
 * empty set, so every `?mode=` request keeps the canonical render (the
 * pre-JOV-12081 behavior) instead of landing on the broken fallback.
 *
 * The generated file is committed with the full alias budget as the default
 * so local dev (which never runs this script) keeps today's behavior.
 */

import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { neon } from '@neondatabase/serverless';

const here = dirname(fileURLToPath(import.meta.url));
const outputPath = resolve(
  here,
  '../lib/routing/generated/profile-mode-prerender-set.ts'
);

/** Mirrors aliasBudgetProfileModeParams (lib/routing/alias-budget-static-params.ts). */
const ALIAS_BUDGET_PAIRS = [
  { username: 'dualipa', profileMode: 'listen' },
  { username: 'dualipa', profileMode: 'subscribe' },
  { username: 'dualipa', profileMode: 'releases' },
  { username: 'dualipa', profileMode: 'tour' },
  { username: 'testartist', profileMode: 'pay' },
];

function resolveDatabaseUrl() {
  // Same variable lib/db reads (lib/db/client/connection.ts reads only
  // env.DATABASE_URL), so the script answers exactly the question
  // generateStaticParams will answer seconds later during `next build`.
  return process.env.DATABASE_URL?.trim() || '';
}

async function readPublicUsernames(databaseUrl) {
  const sql = neon(databaseUrl);
  const handles = [...new Set(ALIAS_BUDGET_PAIRS.map(pair => pair.username))];
  const rows = await sql`
    select username_normalized, is_public
    from creator_profiles
    where username_normalized = any(${handles})
  `;
  const publicUsernames = new Set(
    rows
      .filter(row => row.is_public === true)
      .map(row => String(row.username_normalized).toLowerCase())
  );
  return ALIAS_BUDGET_PAIRS.filter(pair =>
    publicUsernames.has(pair.username)
  ).map(pair => `${pair.username}:${pair.profileMode}`);
}

function serialize(keys) {
  const lines = keys.map(key => `  '${key}',`);
  return `// GENERATED by scripts/write-profile-mode-prerender-set.mjs at build time.
// Do not edit: the proxy rewrites a \`?mode=\` query only for a pair listed
// here, because only these pairs exist as prerendered profile-mode-render
// documents in this build. A pair missing here keeps the canonical render.
// The committed default mirrors the full alias budget for local dev, where
// this script never runs; \`next build\` overwrites it from the build DB.
export const PROFILE_MODE_PRERENDERED_KEYS: readonly string[] = [
${lines.join('\n')}
];
`;
}

const databaseUrl = resolveDatabaseUrl();
let keys = [];
if (!databaseUrl) {
  console.log(
    'profile-mode prerender set: no build database — every ?mode= query keeps the canonical render'
  );
} else {
  try {
    keys = await readPublicUsernames(databaseUrl);
    console.log(
      `profile-mode prerender set: ${keys.length}/${ALIAS_BUDGET_PAIRS.length} alias-budget pairs have a public build profile`
    );
  } catch (error) {
    console.warn(
      'profile-mode prerender set: build database unreachable — every ?mode= query keeps the canonical render',
      error instanceof Error ? error.message : error
    );
    keys = [];
  }
}

mkdirSync(dirname(outputPath), { recursive: true });
writeFileSync(outputPath, serialize(keys));
