#!/usr/bin/env node
/**
 * Precomputes the Jovie chat skill index (name, description, plan) from
 * apps/web/lib/chat/skills/library/<name>/SKILL.md into
 * apps/web/lib/chat/skills/index.generated.ts, so the stable system prompt
 * never reads the disk at request time.
 *
 *   node apps/web/scripts/generate-chat-skill-index.mjs
 *
 * The output is Biome-formatted. lib/chat/thin-harness.test.ts fails when
 * the index no longer matches the SKILL.md files.
 */
import { execFileSync } from 'node:child_process';
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const SKILLS = join(
  dirname(fileURLToPath(import.meta.url)),
  '../lib/chat/skills'
);
const LIBRARY = join(SKILLS, 'library');
const OUT = join(SKILLS, 'index.generated.ts');

function frontmatter(source) {
  const match = /^---\n([\s\S]*?)\n---/.exec(source.replace(/\r\n/g, '\n'));
  const fields = new Map();
  for (const line of match ? match[1].split('\n') : []) {
    const colon = line.indexOf(':');
    if (colon > 0)
      fields.set(line.slice(0, colon).trim(), line.slice(colon + 1).trim());
  }
  return fields;
}

export function buildIndexSource(library = LIBRARY) {
  const entries = readdirSync(library, { withFileTypes: true })
    .filter(entry => entry.isDirectory())
    .map(entry => entry.name)
    .sort()
    .map(folder => {
      const fields = frontmatter(
        readFileSync(join(library, folder, 'SKILL.md'), 'utf8')
      );
      return {
        name: fields.get('name') ?? folder,
        description: fields.get('description') ?? '',
        paidOnly: fields.get('plan') === 'pro',
      };
    });
  return [
    '// Generated by apps/web/scripts/generate-chat-skill-index.mjs from',
    '// lib/chat/skills/library/*/SKILL.md. Do not edit by hand.',
    "import type { ChatSkillEntry } from './registry';",
    '',
    `export const CHAT_SKILL_INDEX: readonly ChatSkillEntry[] = ${JSON.stringify(entries, null, 2)};`,
    '',
  ].join('\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(OUT, buildIndexSource());
  execFileSync('pnpm', ['exec', 'biome', 'format', '--write', OUT], {
    stdio: 'inherit',
  });
  console.log(`wrote ${OUT}`);
}
