SIDECAR = {
    "schema": "jovie.marketing-image/v1",
    "kind": "demo-artist-art",
    "subject": "abstract",
    "demo": True,
    "source": "procedural",
    "generator": "apps/web/scripts/demo-artists/render-demo-covers.py",
    "note": "Invented demo artist imagery. No person, no text, resembles no real release.",
}


def main(only: list[str]) -> None:
    out_dir = OUT / ARTIST
    out_dir.mkdir(parents=True, exist_ok=True)
    for name, (fn, size) in COVERS.items():
        if only and name not in only:
            continue
        img = Image.fromarray((fn() * 255).round().astype(np.uint8), "RGB")
        if size != img.size[0]:
            img = img.resize((size, size), Image.Resampling.LANCZOS)
        path = out_dir / f"{name}.webp"
        img.save(path, "WEBP", quality=74, method=6)
        (out_dir / f"{name}.webp.meta.json").write_text(json.dumps(SIDECAR, indent=2) + "\n")
        print(f"wrote {path.name} ({path.stat().st_size // 1024} KB)")


if __name__ == "__main__":
    main(sys.argv[1:])
