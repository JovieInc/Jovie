#!/usr/bin/env python3
"""Render the invented demo artists' cover art and avatars.

The homepage shows invented demo artists until real artists opt in to be
featured (Tim, 2026-11-08). Their imagery is rendered here: small physically
shaded scenes (sky scattering, clouds, waves that reflect the sky, ridges in
aerial perspective, stars), graded like film stills. Nothing is generated by
a model, so nothing can resemble a real artist's artwork or a real person:
no people, no faces, no text, no music cliches (docs/marketing/IMAGERY.md).

Every cover is graded toward the one cool accent family, so the catalog
reads as one near-monochrome set.

Deterministic: the same seeds give the same pixels. Needs numpy and Pillow.

  python3 apps/web/scripts/demo-artists/render-demo-covers.py
"""

from __future__ import annotations

import json
import math
import sys
from pathlib import Path

import numpy as np
from PIL import Image

SIZE = 640
SUPERSAMPLE = 2
OUT = Path(__file__).resolve().parents[2] / "public" / "img" / "demo-artists"
ARTIST = "ivo-lindqvist"

V3 = np.ndarray


def vec(*c: float) -> np.ndarray:
    return np.array(c, np.float32)


# ---------------------------------------------------------------- noise


def vnoise(x: V3, z: V3, seed: int = 0) -> V3:
    """Hashed value noise on an integer lattice, smooth-interpolated."""
    xi = np.floor(x).astype(np.int64)
    zi = np.floor(z).astype(np.int64)
    fx, fz = x - xi, z - zi

    def h(a, b):
        n = (a * 374761393 + b * 668265263 + seed * 144665) & 0xFFFFFFFF
        n = ((n ^ (n >> 13)) * 1274126177) & 0xFFFFFFFF
        return ((n ^ (n >> 16)) & 0xFFFF) / 65535.0

    u = fx * fx * (3 - 2 * fx)
    v = fz * fz * (3 - 2 * fz)
    top = h(xi, zi) * (1 - u) + h(xi + 1, zi) * u
    bottom = h(xi, zi + 1) * (1 - u) + h(xi + 1, zi + 1) * u
    return (top * (1 - v) + bottom * v).astype(np.float32)


def fbm(x: V3, z: V3, octaves: int = 5, seed: int = 0) -> V3:
    total, amp, norm = 0.0, 1.0, 0.0
    for i in range(octaves):
        total = total + amp * vnoise(x, z, seed + i * 31)
        norm += amp
        amp *= 0.5
        x, z = x * 2.03 + 17.1, z * 2.03 - 9.3
    return total / norm


# ---------------------------------------------------------------- camera


def camera(fov_deg: float, pitch_deg: float, yaw_deg: float = 0.0, size: int = SIZE):
    r = size * SUPERSAMPLE
    ys, xs = np.mgrid[0:r, 0:r].astype(np.float32) / r
    f = 0.5 / math.tan(math.radians(fov_deg) / 2)
    d = np.stack([xs - 0.5, 0.5 - ys, np.full_like(xs, f)], -1)
    d /= np.linalg.norm(d, axis=-1, keepdims=True)
    cp, sp = math.cos(math.radians(pitch_deg)), math.sin(math.radians(pitch_deg))
    d = np.stack([d[..., 0], d[..., 1] * cp + d[..., 2] * sp, -d[..., 1] * sp + d[..., 2] * cp], -1)
    cy, sy = math.cos(math.radians(yaw_deg)), math.sin(math.radians(yaw_deg))
    d = np.stack([d[..., 0] * cy + d[..., 2] * sy, d[..., 1], -d[..., 0] * sy + d[..., 2] * cy], -1)
    return d.astype(np.float32)


def sun_dir(azimuth_deg: float, elevation_deg: float) -> np.ndarray:
    a, e = math.radians(azimuth_deg), math.radians(elevation_deg)
    return vec(math.sin(a) * math.cos(e), math.sin(e), math.cos(a) * math.cos(e))


# ---------------------------------------------------------------- scene


class Scene:
    """Sky, clouds, ridges and point lights, seen along a direction.

    The same environment is what the water reflects, so reflections of the
    sun, the clouds and the headlands come out of one function.
    """

    def __init__(self, **p):
        self.p = p
        self.sun = sun_dir(*p.get("sun", (6.0, 2.0)))

    def sky(self, v: V3) -> V3:
        p = self.p
        el = np.clip(v[..., 1], -0.2, 1)
        cosg = np.clip((v * self.sun).sum(-1), -1, 1)
        g = np.arccos(cosg)
        t = np.clip(el / p.get("gradient", 0.45), 0, 1) ** 0.55
        col = p["horizon"] * (1 - t[..., None]) + p["zenith"] * t[..., None]
        col = col + np.exp(-np.clip(el, 0, None) / 0.035)[..., None] * p["horizon"] * p.get("haze", 0.5)
        glow = p.get("glow", 1.0)
        mie = np.exp(-g / 0.03) * 1.2 + np.exp(-g / 0.16) * 0.22
        trans = np.clip((v[..., 1] + 0.004) / 0.05, 0, 1) ** 1.5
        col = col + (mie * glow * (0.45 + 0.55 * trans))[..., None] * p["light"]
        radius = p.get("sun_radius", 0.016)
        if radius > 0:
            disc = 1 / (1 + np.exp(np.clip((g - radius) / 0.0012, -50, 50))) * trans
            col = col + disc[..., None] * p["light"] * p.get("sun_power", 6.0)
        return col

    def clouds(self, v: V3, col: V3) -> V3:
        p = self.p
        c = p.get("clouds")
        if not c:
            return col
        el = np.maximum(v[..., 1], 1e-3)
        cx = v[..., 0] / el * c.get("scale", 0.9)
        cz = v[..., 2] / el * c.get("scale", 0.9)
        n = fbm(cx * c.get("sx", 0.9), cz * c.get("sz", 0.25), 6, c.get("seed", 11))
        cover = c.get("cover", 0.52)
        dens = np.clip((n - cover) * c.get("sharp", 3.2), 0, 1)
        dens = dens * np.clip((c.get("top", 0.22) - v[..., 1]) / c.get("top", 0.22), 0, 1) * (v[..., 1] > 0)
        g = np.arccos(np.clip((v * self.sun).sum(-1), -1, 1))
        lit = np.exp(-g / c.get("lining", 0.09))[..., None] * p["light"] * c.get("lit", 1.4)
        cloud = c.get("base", vec(0.05, 0.05, 0.1)) + lit * (1 - dens[..., None]) * 0.9
        a = dens[..., None] * c.get("opacity", 0.92)
        return col * (1 - a) + cloud * a

    def ridges(self, v: V3, col: V3) -> V3:
        """Headlands in aerial perspective, far to near."""
        p = self.p
        az = np.arctan2(v[..., 0], v[..., 2])
        el = v[..., 1]
        g = np.arccos(np.clip((v * self.sun).sum(-1), -1, 1))
        for r in p.get("ridges", ()):
            x = az * r["freq"] + r.get("offset", 0.0)
            top = r["base"] + r["amp"] * (fbm(x, np.full_like(x, r.get("seed", 3) * 1.7), 6, r.get("seed", 3)) - 0.5) * 2
            if "slope" in r:
                top = top + r["slope"] * az
            body = (el < top) & (el > -0.0005 if r.get("over_water", True) else True)
            fog = r["fog"]
            tone = r.get("color", vec(0.012, 0.014, 0.025))
            rim = np.exp(-np.clip(top - el, 0, None) / 0.002) * np.exp(-g / 0.25) * r.get("rim", 0.0)
            ridge = tone * (1 - fog) + p["horizon"] * fog * (0.6 + 0.4 * np.exp(-g / 0.4))[..., None]
            ridge = ridge + rim[..., None] * p["light"]
            col = np.where(body[..., None], ridge, col)
        return col

    def lights(self, v: V3, col: V3) -> V3:
        for light in self.p.get("lights", ()):
            d = sun_dir(*light["at"])
            g = np.arccos(np.clip((v * d).sum(-1), -1, 1))
            col = col + (np.exp(-((g / light["size"]) ** 2)) * light["power"])[..., None] * light["color"]
        return col

    def stars(self, v: V3, col: V3) -> V3:
        s = self.p.get("stars")
        if not s:
            return col
        el = v[..., 1]
        if s.get("trails"):
            # Long exposure: stars sweep arcs around the pole.
            pole = sun_dir(*s["pole"])
            ang = np.arccos(np.clip((v * pole).sum(-1), -1, 1))
            ring = ang * s.get("density", 900.0)
            rid = np.floor(ring)
            on = vnoise(rid, rid * 0.0 + 7.0, 5) > s.get("cut", 0.93)
            width = np.exp(-(((ring - rid) - 0.5) / 0.12) ** 2)
            # Each trail covers a part of its circle.
            e1 = np.cross(pole, vec(0, 0, 1))
            e1 = e1 / np.linalg.norm(e1)
            e2 = np.cross(pole, e1)
            phi = np.arctan2((v * e2).sum(-1), (v * e1).sum(-1))
            start = vnoise(rid, rid * 0 + 3.0, 9) * 2 * math.pi
            span = s.get("span", 0.9)
            along = np.mod(phi - start, 2 * math.pi) < span
            bright = vnoise(rid, rid * 0 + 1.0, 13) ** 3 * s.get("power", 1.4)
            trail = on * along * width * bright
            col = col + (trail * (el > 0))[..., None] * s.get("color", vec(0.8, 0.88, 1.0))
        else:
            r = col.shape[0]
            n = vnoise(v[..., 0] * r * 0.9, (v[..., 1] + v[..., 2]) * r * 0.9, 21)
            star = np.clip((n - 0.985) / 0.015, 0, 1) ** 2 * s.get("power", 1.0)
            col = col + (star * np.clip(el / 0.15, 0, 1))[..., None] * s.get("color", vec(0.8, 0.88, 1.0))
        return col

    def environment(self, v: V3) -> V3:
        col = self.sky(v)
        col = self.stars(v, col)
        col = self.clouds(v, col)
        col = self.lights(v, col)
        col = self.ridges(v, col)
        return col

    def water(self, d: V3) -> V3:
        p = self.p
        w = p["water"]
        rng = np.random.default_rng(w.get("seed", 7))
        t = w.get("height", 1.0) / np.maximum(-d[..., 1], 1e-4)
        px, pz = d[..., 0] * t, d[..., 2] * t
        nx = np.zeros_like(px)
        nz = np.zeros_like(px)
        for i in range(w.get("waves", 64)):
            ang = rng.normal(0, w.get("spread", 0.55))
            lam = w.get("length", 2.2) * 0.93**i * rng.uniform(0.6, 1.4)
            k = 2 * math.pi / lam
            amp = w.get("chop", 0.010) * lam * rng.uniform(0.6, 1.2)
            c = np.cos(k * math.sin(ang) * px + k * math.cos(ang) * pz + rng.uniform(0, 2 * math.pi)) * amp * k
            nx += c * math.sin(ang)
            nz += c * math.cos(ang)
        fade = np.exp(-t / 90)
        n = np.stack([-nx * fade, np.ones_like(nx), -nz * fade], -1)
        n /= np.linalg.norm(n, axis=-1, keepdims=True)
        r = d - 2 * (d * n).sum(-1, keepdims=True) * n
        r[..., 1] = np.abs(r[..., 1])
        cosi = np.clip(-(d * n).sum(-1), 0, 1)
        fresnel = 0.02 + 0.98 * (1 - cosi) ** 5
        col = self.environment(r) * fresnel[..., None] + w.get("deep", vec(0.01, 0.012, 0.03)) * (1 - fresnel[..., None])
        spec = np.clip((r * self.sun).sum(-1), 0, 1)
        glitter = (spec**900 * 3.0 + spec**120 * 0.25) * np.exp(-t / 400) * w.get("glitter", 1.0)
        col = col + glitter[..., None] * p["light"]
        fog = 1 - np.exp(-t / w.get("fog", 180))
        return col * (1 - fog[..., None]) + p["horizon"] * fog[..., None]

    def render(self) -> V3:
        p = self.p
        d = camera(p.get("fov", 42), p.get("pitch", 4.0), p.get("yaw", 0.0))
        img = np.zeros(d.shape, np.float32)
        up = d[..., 1] > 0 if "water" in p else np.ones(d.shape[:2], bool)
        img[up] = self.environment(d[up])
        if "water" in p:
            img[~up] = self.water(d[~up])
        n = d.shape[0] // SUPERSAMPLE
        return img.reshape(n, SUPERSAMPLE, n, SUPERSAMPLE, 3).mean((1, 3))


# ---------------------------------------------------------------- film


def blur(a: V3, radius: float, axis: str = "both") -> V3:
    h, w = a.shape[:2]
    fy = np.fft.fftfreq(h)[:, None]
    fx = np.fft.fftfreq(w)[None, :]
    if axis == "x":
        k = np.exp(-2 * math.pi**2 * radius**2 * fx**2) * np.ones_like(fy)
    else:
        k = np.exp(-2 * math.pi**2 * radius**2 * (fx**2 + fy**2))
    out = np.empty_like(a)
    for c in range(a.shape[2]):
        out[..., c] = np.real(np.fft.ifft2(np.fft.fft2(a[..., c]) * k))
    return out


def film(img: V3, seed: int, exposure=0.95, streak=1.2, bloom=1.0, grain=0.018, vignette=0.42, tint=None) -> V3:
    bright = np.clip(img - 0.9, 0, None)
    img = img + (blur(bright, 6) * 0.6 + blur(bright, 30) * 0.35) * bloom
    img = img + blur(bright, 90, "x") * vec(0.55, 0.6, 1.0) * streak
    img = img * exposure
    img = 1 - np.exp(-img * 1.6)
    img /= 1 - math.exp(-1.6)
    if tint is not None:
        # Split-tone toward the one accent family: shadows and mids lean
        # cool, highlights stay near white.
        lum = (img * vec(0.2126, 0.7152, 0.0722)).sum(-1, keepdims=True)
        img = img * (1 - tint[1]) + (lum * tint[0]) * tint[1] / max(float(tint[0].max()), 1e-6)
    n = img.shape[0]
    yy, xx = np.mgrid[0:n, 0:n] / n
    v = ((xx - 0.5) ** 2 + (yy - 0.5) ** 2) / 0.5
    img = img * (1 - vignette * v[..., None])
    lum = img.mean(2, keepdims=True)
    img = img + np.random.default_rng(seed).normal(0, grain, (n, n, 1)) * (0.3 + 0.7 * np.sqrt(np.clip(lum, 0, 1)))
    return np.clip(img, 0, 1)


