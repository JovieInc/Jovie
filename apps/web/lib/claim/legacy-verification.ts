/**
 * Grandfathered claims (Tim, 2026-11-01, claim-verify spec Q2).
 *
 * Profiles that were claimed and public before proof-before-public shipped are
 * recorded as `verified` with `proofMethod: 'legacy'` (migration 0164). They
 * stay public. Proof becomes mandatory only when:
 *
 *   - the claim is disputed, or
 *   - the artist has 50k+ Spotify followers and the 30-day nudge window has
 *     passed without a real proof.
 *
 * In the reach case the daily sweep (`legacy-verification.server.ts`) turns
 * the record into a proof-only `pending_verification` request, so the
 * `creator_profiles_proof_before_public` trigger makes the page private until
 * proof or an operator decision. A disputed page is left to the dispute flow,
 * which freezes it but keeps it up (spec section 6).
 *
 * Pure module: no I/O.
 */

import {
  type ClaimVerificationRecord,
  readClaimVerification,
  requiresClaimVerification,
} from './claim-verification';

/** `decidedBy` on every record the grandfather migration wrote. */
export const LEGACY_GRANDFATHER_DECIDED_BY = 'grandfather-2026-11' as const;

export const LEGACY_NUDGE_WINDOW_DAYS = 30;

export type LegacyVerificationState = 'ok' | 'nudge' | 'proof_required';

/** Payload the dashboard reads; no UI renders it yet. */
export interface LegacyNudge {
  readonly state: Exclude<LegacyVerificationState, 'ok'>;
  /** End of the 30-day window, ISO. */
  readonly dueAt: string | null;
  /** When the nudge stage was first recorded, ISO. */
  readonly nudgeSentAt: string | null;
}

function isPastDue(record: ClaimVerificationRecord, now: Date): boolean {
  const due = Date.parse(record.legacyNudgeDueAt ?? '');
  // A missing or malformed due date fails closed: the window is over.
  return !Number.isFinite(due) || now.getTime() >= due;
}

/**
 * `currentReach` is the live follower count when the caller has it; the
 * larger of it and the recorded reach decides, so growth after the migration
 * counts and a missing count never lowers the bar.
 */
export function legacyVerificationState(
  record: ClaimVerificationRecord | null,
  now: Date,
  currentReach?: number | null
): LegacyVerificationState {
  if (record?.proofMethod !== 'legacy') return 'ok';
  if (record.status === 'disputed') return 'proof_required';
  if (record.status !== 'verified') return 'ok';
  const reach = Math.max(record.reach.value ?? 0, currentReach ?? 0);
  if (requiresClaimVerification(reach) && isPastDue(record, now)) {
    return 'proof_required';
  }
  return 'nudge';
}

/** Records the nudge stage once. Null when there is nothing to record. */
export function markLegacyNudgeSent(
  record: ClaimVerificationRecord | null,
  now: Date,
  currentReach?: number | null
): ClaimVerificationRecord | null {
  if (!record || record.nudgeSentAt) return null;
  if (legacyVerificationState(record, now, currentReach) !== 'nudge') {
    return null;
  }
  return { ...record, nudgeSentAt: now.toISOString() };
}

/**
 * High-reach legacy claim past its window: reopen as a proof-only request.
 * `proofMethod` and the grandfather decision are cleared so an operator
 * approval later is a real decision, not another legacy record. Returns null
 * for anything else, including disputes, so repeated runs are no-ops.
 */
export function requireLegacyProof(
  record: ClaimVerificationRecord | null,
  input: {
    readonly now: Date;
    readonly currentReach?: number | null;
    /** Generated by the caller (random), so this module stays pure. */
    readonly proofCode: string;
  }
): ClaimVerificationRecord | null {
  if (record?.status !== 'verified') return null;
  if (
    legacyVerificationState(record, input.now, input.currentReach) !==
    'proof_required'
  ) {
    return null;
  }
  const {
    proofMethod: _proofMethod,
    decidedAt: _decidedAt,
    decidedBy: _decidedBy,
    decisionReason: _decisionReason,
    ...rest
  } = record;
  return {
    ...rest,
    status: 'pending_verification',
    proofOnly: true,
    proofCode: input.proofCode,
    reach: {
      ...record.reach,
      value: Math.max(record.reach.value ?? 0, input.currentReach ?? 0),
    },
    legacyProofRequiredAt: input.now.toISOString(),
  };
}

export function legacyNudgeForDashboard(
  settings: unknown,
  now: Date
): LegacyNudge | null {
  const record = readClaimVerification(settings);
  const state = legacyVerificationState(record, now);
  if (!record || state === 'ok') return null;
  return {
    state,
    dueAt: record.legacyNudgeDueAt ?? null,
    nudgeSentAt: record.nudgeSentAt ?? null,
  };
}
